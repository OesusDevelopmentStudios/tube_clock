"""Generate lib/clockcore/src/clockcore/TzTable.cpp from the system tz database.

The firmware menu offers this curated list of zones. Each entry stores the
POSIX TZ rule taken from the footer line of the compiled TZif file, so DST
transitions are applied by the C library on the clock.

Europe/Dublin and Africa/Casablanca are deliberately left out. Dublin uses
"negative" DST (IST is the standard time, GMT the winter DST), which breaks the
"no summer time" option, and the Casablanca footer does not describe its real
offset (tzdata lists explicit transitions instead).

Usage: python3 scripts/gen_tz_table.py [--zoneinfo /usr/share/zoneinfo]
"""
import argparse
import pathlib

ZONES = [
    "Etc/UTC",
    # Europe
    "Europe/London", "Europe/Lisbon", "Europe/Madrid", "Europe/Paris",
    "Europe/Brussels", "Europe/Amsterdam", "Europe/Berlin", "Europe/Zurich", "Europe/Rome",
    "Europe/Vienna", "Europe/Prague", "Europe/Bratislava", "Europe/Warsaw", "Europe/Budapest",
    "Europe/Copenhagen", "Europe/Oslo", "Europe/Stockholm", "Europe/Helsinki", "Europe/Tallinn",
    "Europe/Riga", "Europe/Vilnius", "Europe/Bucharest", "Europe/Sofia", "Europe/Athens",
    "Europe/Kyiv", "Europe/Istanbul", "Europe/Moscow",
    # Americas
    "America/St_Johns", "America/Halifax", "America/New_York", "America/Chicago",
    "America/Denver", "America/Phoenix", "America/Los_Angeles", "America/Anchorage",
    "Pacific/Honolulu", "America/Mexico_City", "America/Bogota", "America/Lima",
    "America/Santiago", "America/Sao_Paulo", "America/Argentina/Buenos_Aires",
    # Africa / Middle East
    "Atlantic/Reykjavik", "Africa/Lagos", "Africa/Cairo",
    "Africa/Johannesburg", "Africa/Nairobi", "Asia/Jerusalem", "Asia/Riyadh", "Asia/Tehran",
    "Asia/Dubai",
    # Asia / Pacific
    "Asia/Karachi", "Asia/Kolkata", "Asia/Kathmandu", "Asia/Dhaka", "Asia/Bangkok",
    "Asia/Jakarta", "Asia/Singapore", "Asia/Shanghai", "Asia/Hong_Kong", "Asia/Taipei",
    "Asia/Manila", "Asia/Seoul", "Asia/Tokyo", "Australia/Perth", "Australia/Darwin",
    "Australia/Brisbane", "Australia/Adelaide", "Australia/Sydney", "Pacific/Auckland",
]

HEADER = """// SPDX-License-Identifier: GPL-3.0-or-later
// GENERATED by scripts/gen_tz_table.py - do not edit by hand.
#include "clockcore/TzTable.hpp"

namespace clockcore {

static const TzEntry kZones[] = {
"""

FOOTER = """};

const TzEntry *tzTable() { return kZones; }
int tzTableSize() { return static_cast<int>(sizeof(kZones) / sizeof(kZones[0])); }

} // namespace clockcore
"""


def posix_rule(zoneinfo: pathlib.Path, zone: str) -> str:
    data = (zoneinfo / zone).read_bytes()
    footer = data.rstrip(b"\n").rsplit(b"\n", 1)[-1].decode("ascii")
    if not footer:
        raise SystemExit(f"{zone}: no POSIX footer in TZif file")
    return footer


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--zoneinfo", default="/usr/share/zoneinfo", type=pathlib.Path)
    ap.add_argument("--out", default="lib/clockcore/src/clockcore/TzTable.cpp", type=pathlib.Path)
    args = ap.parse_args()
    lines = [HEADER]
    for zone in ZONES:
        lines.append(f'    {{"{zone}", "{posix_rule(args.zoneinfo, zone)}"}},\n')
    lines.append(FOOTER)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("".join(lines), newline="\n")
    print(f"wrote {len(ZONES)} zones to {args.out}")


if __name__ == "__main__":
    main()
